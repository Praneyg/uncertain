"""Collect what a user sees without reading source: public signatures, docstrings, and the
error raised when each axis is misused. Output: eval/usability_evidence.md (graded by an LLM
against the rubric in eval/usability_grading.md)."""
import inspect
import sys
from pathlib import Path

EVAL = Path(__file__).resolve().parent
sys.path.insert(0, str(EVAL))
import uncertain  # noqa: E402
from uncertain import Measure, MeasureSpec, SamplingSpec, Sampler, Sweep, ConfigError  # noqa: E402
from toy_lm import ToyLM  # noqa: E402

OBJECTS = ["Measure", "Measure.from_config", "Measure.replace", "Measure.compute", "MeasureSpec",
           "SamplingSpec", "UnitSpec", "EncoderSpec", "StatisticSpec", "Sampler", "Sampler.sample",
           "Sampler.extend", "Sweep", "Result", "surprisal", "information_value", "entropy",
           "contextual_probability", "register_distance", "Stimulus"]


def doc_of(path):
    obj = uncertain
    for part in path.split("."):
        obj = getattr(obj, part)
    try:
        sig = str(inspect.signature(obj))
    except (TypeError, ValueError):
        sig = "(signature unavailable)"
    return sig, inspect.getdoc(obj) or "(no docstring)"


def error_of(fn):
    try:
        fn()
        return "(no error)"
    except Exception as exc:  # noqa: BLE001 -- recording the message is the point
        return f"{type(exc).__name__}: {exc}"


def main():
    lm = ToyLM([.5, .5])
    s = SamplingSpec(lm.model_spec, n=4, seed=0)
    probes = {
        "unit": lambda: MeasureSpec(s, 1, "compare_ragged", unit="morpheme"),
        "horizon": lambda: MeasureSpec(s, 0, "compare_ragged"),
        "level": lambda: Measure(MeasureSpec(s, 1, "compare_ragged", representation="layer:2"),
                                 sampler=Sampler(uncertain.ToyBackend())),
        "distance": lambda: Measure(MeasureSpec(s, 1, "compare_ragged", distance="cosine"), sampler=Sampler(lm)),
        "aggregation": lambda: Measure(MeasureSpec(s, 1, "compare_ragged", statistic="median"), sampler=Sampler(lm)),
        "set size": lambda: Measure.from_config(lm, short_samples="pad"),
        "short-sample policy": lambda: Measure.from_config(lm, n=4),
        "short-sample policy (bad value)": lambda: MeasureSpec(s, 1, "ignore"),
    }
    out = ["# Usability evidence (auto-generated by eval/usability_evidence.py)", ""]
    out += ["## Public names", "", "`uncertain.__all__` = " + ", ".join(f"`{n}`" for n in uncertain.__all__), ""]
    out += ["## Signatures and docstrings", ""]
    for name in OBJECTS:
        sig, doc = doc_of(name)
        out += [f"### `{name}{sig}`", "", "```", doc, "```", ""]
    out += ["## Errors on misuse, per axis", ""]
    for axis, fn in probes.items():
        out += [f"- **{axis}**: `{error_of(fn)}`"]
    readme = (EVAL.parent / "README.md").read_text(encoding="utf-8")
    out += ["", "## README.md (verbatim)", "", readme]
    (EVAL / "usability_evidence.md").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
